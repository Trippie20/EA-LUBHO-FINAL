import { makeEnv, makeClient, makeRunner } from './helpers.mjs';
const { check, section, finish } = makeRunner();
const env = makeEnv();
const admin = makeClient(env), alice = makeClient(env), bob = makeClient(env), anon = makeClient(env);

section('Setup');
let r = await anon.call('GET', '/setup/status');
check('needs setup at first', r.needsSetup === true);
r = await anon.call('POST', '/setup', { body: { setupToken: 'nope', email: 'a@x.com', name: 'A', password: 'long-enough-pass' } });
check('wrong setup token refused', r.status === 403);
r = await admin.call('POST', '/setup', { body: { setupToken: env.SETUP_TOKEN, email: 'Admin@x.com', name: 'Admin', password: 'long-enough-pass' } });
check('super admin created', r.ok && r.user.role === 'super_admin', JSON.stringify(r));
r = await anon.call('POST', '/setup', { body: { setupToken: env.SETUP_TOKEN, email: 'b@x.com', name: 'B', password: 'long-enough-pass' } });
check('setup cannot run twice', r.status === 409);
r = await admin.call('POST', '/auth/login', { body: { email: 'admin@x.com', password: 'long-enough-pass' } });
check('admin logs in', r.ok && admin.jar.lubho_session);
const stored = env.DB.raw.prepare('SELECT pw_hash FROM users').get();
check('password not stored in plain text', !stored.pw_hash.includes('long-enough'));

section('Registration and login');
r = await alice.call('POST', '/auth/register', { body: { email: 'alice@x.com', name: 'Alice', password: 'short' } });
check('short password rejected', r.status === 400);
r = await alice.call('POST', '/auth/register', { body: { email: 'alice@x.com', name: 'Alice', password: 'Wonderland-9921' } });
check('register ok and logged in', r.ok && alice.jar.lubho_session);
r = await bob.call('POST', '/auth/register', { body: { email: 'alice@x.com', name: 'X', password: 'Wonderland-9921' } });
check('duplicate email refused', r.status === 409);
await bob.call('POST', '/auth/register', { body: { email: 'bob@x.com', name: 'Bob', password: 'Builder-pass-77' } });
r = await alice.call('GET', '/me');
check('/me returns user', r.user?.email === 'alice@x.com');
r = await anon.call('GET', '/me');
check('/me needs login', r.status === 401);
r = await alice.call('POST', '/auth/register', { body: { email: 'z@x.com', name: 'Z', password: 'Wonderland-9921' }, csrf: false });
check('csrf header required on register', r.status === 403);

section('Roles');
r = await alice.call('GET', '/admin/users');
check('user cannot list users', r.status === 403);
r = await anon.call('GET', '/admin/users');
check('anonymous cannot list users', r.status === 401);
r = await admin.call('GET', '/admin/users');
check('admin lists users', r.ok && r.users.length === 3);
r = await admin.call('GET', '/admin/users?q=ali');
check('search works', r.users.length === 1);
check('no hashes leaked', !JSON.stringify(r).includes('pw_'));

section('Admin controls');
const aliceId = (await alice.call('GET', '/me')).user.id;
r = await admin.call('POST', `/admin/users/${aliceId}/suspend`);
check('suspend ok', r.ok);
r = await alice.call('GET', '/me');
check('suspended user locked out', r.status === 401);
r = await alice.call('POST', '/auth/login', { body: { email: 'alice@x.com', password: 'Wonderland-9921' } });
check('suspended user cannot log in', r.status === 403);
await admin.call('POST', `/admin/users/${aliceId}/restore`);
r = await admin.call('POST', `/admin/users/${aliceId}/reset-password`);
check('temp password issued', r.ok && r.temporaryPassword.length === 16);
const temp = r.temporaryPassword;
r = await alice.call('POST', '/auth/login', { body: { email: 'alice@x.com', password: temp } });
check('temp password works, must change', r.ok && r.user.mustChange === true);
r = await alice.call('POST', '/me/password', { body: { current: temp, next: 'New-Strong-Pass-5' } });
check('password changed', r.ok);
r = await alice.call('GET', '/me');
check('mustChange cleared', r.user.mustChange === false);
const adminId = (await admin.call('GET', '/me')).user.id;
r = await admin.call('POST', `/admin/users/${adminId}/suspend`);
check('cannot suspend self', r.status === 409);
r = await admin.call('GET', '/admin/users');
check('activity logged', env.DB.raw.prepare("SELECT COUNT(*) c FROM activity_logs WHERE action='admin.user_suspend'").get().c === 1);

section('Brute force');
const eve = makeClient(env);
let last;
for (let i = 0; i < 12; i++) last = await eve.call('POST', '/auth/login', { body: { email: 'bob@x.com', password: 'wrong' + i } });
check('login rate limited', last.status === 429);

section('Logout and delete');
r = await bob.call('POST', '/auth/logout');
check('logout ok', r.ok);
r = await bob.call('GET', '/me');
check('session gone', r.status === 401);
r = await alice.call('DELETE', '/me', { body: { password: 'New-Strong-Pass-5' } });
check('self delete ok', r.ok);
r = await admin.call('GET', '/admin/users');
check('user removed', r.users.length === 2);
finish();
