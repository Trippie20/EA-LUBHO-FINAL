// Approval, hosting configuration, live monitor, analytics, settings, live-account gate.
import { makeEnv, makeClient, makeRunner } from './helpers.mjs';
const { check, section, finish } = makeRunner();
const env = makeEnv();
const admin = makeClient(env), alice = makeClient(env), bob = makeClient(env), anon = makeClient(env), agentNet = makeClient(env);
await admin.call('POST', '/setup', { body: { setupToken: env.SETUP_TOKEN, email: 'admin@x.com', name: 'Admin', password: 'long-enough-pass' } });
await admin.call('POST', '/auth/login', { body: { email: 'admin@x.com', password: 'long-enough-pass' } });
const ag = (token) => ({
  poll: (body = {}) => agentNet.call('POST', '/agent/poll', { body: { agentVersion: '1', info: { os: 'Windows' }, ...body }, token, csrf: false }),
  result: (id, body) => agentNet.call('POST', `/agent/tasks/${id}/result`, { body, token, csrf: false }),
});

section('User approval');
let r = await anon.call('GET', '/setup/status');
check('approval off by default in a fresh test env', r.approvalRequired === false);
r = await alice.call('GET', '/admin/settings');
check('settings are admin only', r.status === 401 || r.status === 403);
r = await admin.call('PUT', '/admin/settings', { body: { requireApproval: 'yes' } });
check('settings validated', r.status === 400);
r = await admin.call('PUT', '/admin/settings', { body: { requireApproval: true } });
check('admin turns approval on', r.ok);
r = await anon.call('GET', '/setup/status');
check('register screen can tell approval is on', r.approvalRequired === true);
r = await alice.call('POST', '/auth/register', { body: { email: 'alice@x.com', name: 'Alice', password: 'Wonderland-9921' } });
check('registration is pending, no login', r.ok && r.pending === true && !alice.jar.lubho_session);
r = await alice.call('POST', '/auth/login', { body: { email: 'alice@x.com', password: 'Wonderland-9921' } });
check('pending user cannot log in', r.status === 403 && r.error === 'pending');
r = await admin.call('GET', '/notifications');
check('admin notified of pending user', r.notifications.some((n) => n.title.includes('waiting for approval')));
r = await admin.call('GET', '/admin/stats');
check('pending counted separately', r.stats.usersPending === 1 && r.stats.users === 0);
const aliceId = (await admin.call('GET', '/admin/users?q=alice')).users[0].id;
r = await alice.call('POST', `/admin/users/${aliceId}/approve`);
check('user cannot approve themselves', r.status === 401 || r.status === 403);
r = await admin.call('POST', `/admin/users/${aliceId}/approve`);
check('admin approves', r.ok);
r = await admin.call('POST', `/admin/users/${aliceId}/approve`);
check('cannot approve an active user', r.status === 409);
r = await alice.call('POST', '/auth/login', { body: { email: 'alice@x.com', password: 'Wonderland-9921' } });
check('approved user logs in', r.ok);
r = await alice.call('GET', '/notifications');
check('user told they were approved', r.notifications.some((n) => n.title === 'Account approved'));
await bob.call('POST', '/auth/register', { body: { email: 'bob@x.com', name: 'Bob', password: 'Builder-pass-77' } });
const bobId = (await admin.call('GET', '/admin/users?q=bob')).users[0].id;
r = await admin.call('POST', `/admin/users/${bobId}/reject`);
check('admin rejects', r.ok);
r = await bob.call('POST', '/auth/login', { body: { email: 'bob@x.com', password: 'Builder-pass-77' } });
check('rejected user blocked with clear message', r.status === 403 && r.error === 'rejected');
await admin.call('PUT', '/admin/settings', { body: { requireApproval: false } });
await bob.call('POST', `/admin/users/${bobId}/approve`);
await admin.call('POST', `/admin/users/${bobId}/approve`);
await bob.call('POST', '/auth/login', { body: { email: 'bob@x.com', password: 'Builder-pass-77' } });
const carol = makeClient(env);
r = await carol.call('POST', '/auth/register', { body: { email: 'carol@x.com', name: 'Carol', password: 'Zebra-pass-4455' } });
check('with approval off, registration logs in directly', r.ok && !r.pending && carol.jar.lubho_session, JSON.stringify(r));

section('Live accounts stay off during testing');
r = await alice.call('POST', '/accounts', { body: { login: '9000001', server: 'Real-Server', password: 'real-money-pw', kind: 'live' } });
check('live account refused', r.status === 409 && r.error === 'live_disabled');
const env2 = makeEnv({ ALLOW_LIVE_ACCOUNTS: 'true' });
const adm2 = makeClient(env2), u2 = makeClient(env2);
await adm2.call('POST', '/setup', { body: { setupToken: env2.SETUP_TOKEN, email: 'a@x.com', name: 'A', password: 'long-enough-pass' } });
await u2.call('POST', '/auth/register', { body: { email: 'u@x.com', name: 'U', password: 'Unique-pass-3321' } });
r = await u2.call('POST', '/accounts', { body: { login: '9000001', server: 'Real-Server', password: 'real-money-pw', kind: 'live' } });
check('live account allowed only when the Cloudflare flag is set', r.ok);

section('Host, account, EA');
const host = await admin.call('POST', '/admin/hosts', { body: { name: 'HP laptop' } });
const g = ag(host.token);
const acc = (await alice.call('POST', '/accounts', { body: { login: '5550001', server: 'Demo-Server', password: 'MT5-secret-pw!' } })).id;
let t = await g.poll(); await g.result(t.task.id, { ok: true, info: { balance: 1000, currency: 'USD' } });
const ea = (await alice.call('POST', '/eas', { body: { name: 'Jumbo' } })).id;
const file = (await alice.call('POST', `/eas/${ea}/files?name=Jumbo.ex5`, { raw: new Uint8Array(300).fill(5) })).id;

section('Client hosting configuration');
r = await alice.call('POST', '/sessions', { body: { accountId: acc, fileId: file, symbol: 'XAUUSD; rm -rf', timeframe: 'M5' } });
check('bad symbol rejected', r.status === 400);
r = await alice.call('POST', '/sessions', { body: { accountId: acc, fileId: file, symbol: 'XAUUSD.m', timeframe: 'M7' } });
check('bad timeframe rejected', r.status === 400);
r = await alice.call('POST', '/sessions', { body: { accountId: acc, fileId: file, symbol: 'XAUUSD.m', timeframe: 'm5', preset: 'x'.repeat(20001) } });
check('oversized preset rejected', r.status === 400);
r = await alice.call('POST', '/sessions', { body: { accountId: acc, fileId: file, symbol: 'XAUUSD.m', timeframe: 'm5', preset: 'Lots=0.01\nMaxTrades=2\n', presetName: 'my preset' } });
check('session created with configuration', r.ok);
const sid = r.id;
r = await alice.call('GET', `/sessions/${sid}`);
check('config visible, preset text not echoed in list', r.session.symbol === 'XAUUSD.m' && r.session.timeframe === 'M5' && r.session.presetName === 'my preset.set' && r.session.hasPreset === true && !JSON.stringify(r).includes('MaxTrades'));
t = await g.poll();
check('agent receives symbol, timeframe and preset', t.task.type === 'start_session' && t.task.config.symbol === 'XAUUSD.m' && t.task.config.timeframe === 'M5' && t.task.config.preset.includes('MaxTrades=2') && t.task.config.presetName === 'my preset.set');
r = await alice.call('PATCH', `/sessions/${sid}/config`, { body: { symbol: 'EURUSD' } });
check('cannot change config while starting', r.status === 409);
await g.result(t.task.id, { ok: true, detail: 'started' });

section('Live Trade Monitor (read-only snapshots reported by the host)');
r = await alice.call('GET', '/monitor');
check('before any report: no snapshot, not invented', r.items.length === 1 && r.items[0].snapshot === null && r.items[0].floatingProfit === null);
const pos = [{ ticket: '77', symbol: 'XAUUSD.m', type: 'buy', volume: 0.01, openPrice: 2300.5, profit: 4.25, openedAt: env.clock - 60000 }, { ticket: '78', symbol: 'XAUUSD.m', type: 'sell', volume: 0.02, openPrice: 2301, profit: -1.5, openedAt: env.clock }];
await g.poll({ running: [sid], monitor: [{ sessionId: sid, balance: 1000.5, equity: 1003.25, margin: 12, freeMargin: 990, currency: 'USD', positions: pos }] });
r = await alice.call('GET', '/monitor');
check('snapshot stored and shown', r.items[0].snapshot.equity === 1003.25 && r.items[0].snapshot.positions.length === 2 && r.items[0].floatingProfit === 2.75 && r.items[0].stale === false);
await g.poll({ running: [sid], monitor: [{ sessionId: sid, balance: 1, equity: 1, positions: [] }] });
r = await alice.call('GET', '/monitor');
check('snapshots are throttled (30s)', r.items[0].snapshot.balance === 1000.5);
r = await g.poll({ running: [sid], monitor: [{ sessionId: 'not-mine', balance: 5 }] });
check('snapshot for an unknown session ignored', r.ok);
env.clock += 31_000;
await g.poll({ running: [sid], monitor: [{ sessionId: sid, balance: 1010, equity: 1020, currency: 'USD', positions: [{ ticket: '<script>', symbol: 'X'.repeat(80), profit: 'abc' }] }] });
r = await alice.call('GET', '/monitor');
check('reported text is clamped and non-numbers dropped', r.items[0].snapshot.positions[0].symbol.length <= 24 && r.items[0].snapshot.positions[0].profit === null);
r = await bob.call('GET', '/monitor');
check("bob cannot see alice's accounts", r.items.length === 0);
r = await alice.call('GET', '/accounts');
check('account balance card updated from snapshot', r.accounts[0].info.balance === 1010);
env.clock += 4 * 60_000;
await g.poll({ running: [sid] });
r = await alice.call('GET', '/monitor');
check('old snapshot flagged stale', r.items[0].stale === true);

section('Analytics Centre');
r = await alice.call('GET', '/analytics');
check('user analytics from stored data', r.analytics.sessions.total === 1 && r.analytics.sessions.running === 1 && r.analytics.byEa[0].name === 'Jumbo' && r.analytics.files === 1);
check('equity history from snapshots, per account', r.analytics.equity.length === 1 && r.analytics.equity[0].points.length === 2);
check('no win rate / trade history invented', r.analytics.winRate === undefined && r.analytics.netProfit === undefined);
r = await bob.call('GET', '/analytics');
check('analytics are per user', r.analytics.sessions.total === 0 && r.analytics.equity.length === 0);
r = await alice.call('GET', '/admin/analytics');
check('platform analytics admin only', r.status === 403);
r = await admin.call('GET', '/admin/analytics');
check('platform analytics', r.analytics.registrations.length === 30 && r.analytics.sessionsTotal === 1 && r.analytics.registrations.reduce((a, d) => a + d.count, 0) >= 3 && r.analytics.topEas[0].name === 'Jumbo');

section('Stop, edit configuration, restart');
await alice.call('POST', `/sessions/${sid}/stop`);
t = await g.poll({ running: [sid] }); await g.result(t.task.id, { ok: true, detail: 'closed' });
r = await alice.call('PATCH', `/sessions/${sid}/config`, { body: { symbol: 'EURUSD', timeframe: 'H1', preset: '' } });
check('config editable once stopped', r.ok);
r = await alice.call('GET', `/sessions/${sid}`);
check('new config saved, preset cleared', r.session.symbol === 'EURUSD' && r.session.timeframe === 'H1' && r.session.hasPreset === false);
r = await bob.call('PATCH', `/sessions/${sid}/config`, { body: { symbol: 'X' } });
check("bob cannot edit alice's config", r.status === 404);
await alice.call('POST', `/sessions/${sid}/restart`);
t = await g.poll({ running: [] });
check('restart uses the saved config', t.task.config.symbol === 'EURUSD' && t.task.config.timeframe === 'H1' && t.task.config.preset === '');
finish();
