import { makeEnv, makeClient, makeRunner, makeR2 } from './helpers.mjs';
const { check, section, finish } = makeRunner();

async function world(extra) {
  const env = makeEnv(extra);
  const admin = makeClient(env), alice = makeClient(env), bob = makeClient(env);
  await admin.call('POST', '/setup', { body: { setupToken: env.SETUP_TOKEN, email: 'admin@x.com', name: 'Admin', password: 'long-enough-pass' } });
  await admin.call('POST', '/auth/login', { body: { email: 'admin@x.com', password: 'long-enough-pass' } });
  await alice.call('POST', '/auth/register', { body: { email: 'alice@x.com', name: 'Alice', password: 'Wonderland-9921' } });
  await bob.call('POST', '/auth/register', { body: { email: 'bob@x.com', name: 'Bob', password: 'Builder-pass-77' } });
  return { env, admin, alice, bob };
}
const ex5 = (n = 400, fill = 7) => { const b = new Uint8Array(n).fill(fill); b[0] = 0x01; return b; };
const up = (c, id, name, bytes) => c.call('POST', `/eas/${id}/files?name=${encodeURIComponent(name)}`, { raw: bytes, headers: { 'content-type': 'application/octet-stream' } });

for (const mode of ['d1', 'r2']) {
  section(`EAs and files (${mode} storage)`);
  const { env, admin, alice, bob } = await world(mode === 'r2' ? { FILES: makeR2() } : {});
  let r = await alice.call('POST', '/eas', { body: { name: '', version: '1' } });
  check('empty name rejected', r.status === 400);
  r = await alice.call('POST', '/eas', { body: { name: 'Jumbo Scalper', version: '1.2', description: 'test' } });
  check('EA created', r.ok);
  const eaId = r.id;
  r = await up(alice, eaId, 'Jumbo.ex5', ex5(1_000_000, 9));
  check('upload ok', r.ok && r.size === 1_000_000, JSON.stringify(r));
  const fileId = r.id;
  r = await up(alice, eaId, 'virus.exe', ex5());
  check('non-ex5 name rejected', r.status === 400);
  const exe = ex5(); exe[0] = 0x4d; exe[1] = 0x5a;
  r = await up(alice, eaId, 'fake.ex5', exe);
  check('executable disguised as ex5 rejected', r.status === 400);
  r = await up(alice, eaId, 'Tiny.ex5', new Uint8Array(4));
  check('tiny file rejected', r.status === 400);
  r = await up(alice, eaId, 'Big.ex5', ex5(mode === 'r2' ? 21 * 1048576 : 3 * 1048576 + 1));
  check('oversize rejected', r.status === 413);
  r = await alice.call('GET', `/files/${fileId}/download`);
  check('owner downloads identical bytes', r.status === 200 && r.bytes.length === 1_000_000 && r.bytes[5] === 9 && r.bytes[0] === 1);
  r = await bob.call('GET', `/files/${fileId}/download`);
  check("other user cannot download", r.status === 404);
  r = await bob.call('GET', `/eas/${eaId}`);
  check("other user cannot see unpublished EA", r.status === 404);
  r = await bob.call('PATCH', `/eas/${eaId}`, { body: { name: 'hacked' } });
  check('other user cannot edit', r.status === 404);
  r = await bob.call('DELETE', `/files/${fileId}`);
  check('other user cannot delete file', r.status === 404);
  r = await admin.call('GET', `/files/${fileId}/download`);
  check('admin can download', r.status === 200);
  r = await alice.call('POST', `/admin/eas/${eaId}/status`, { body: { status: 'published' } });
  check('user cannot publish', r.status === 403);
  r = await admin.call('POST', `/admin/eas/${eaId}/status`, { body: { status: 'published' } });
  check('admin publishes', r.ok);
  r = await bob.call('GET', '/catalogue');
  check('published EA in catalogue, no owner info', r.eas.length === 1 && !JSON.stringify(r).includes('alice@'));
  r = await bob.call('GET', `/eas/${eaId}`);
  check('catalogue view shows no files', r.ok && r.files.length === 0);
  r = await bob.call('GET', `/files/${fileId}/download`);
  check('published does not expose file', r.status === 404);
  const empty = (await alice.call('POST', '/eas', { body: { name: 'Empty' } })).id;
  r = await admin.call('POST', `/admin/eas/${empty}/status`, { body: { status: 'published' } });
  check('cannot publish EA without files', r.status === 409);
  r = await alice.call('PATCH', `/eas/${eaId}`, { body: { version: '1.3' } });
  r = await alice.call('GET', `/eas/${eaId}`);
  check('edit saved', r.ea.version === '1.3' && r.ea.name === 'Jumbo Scalper');
  r = await admin.call('GET', '/admin/files');
  check('admin file list', r.files.length === 1 && r.totalBytes === 1_000_000);
  r = await alice.call('DELETE', `/files/${fileId}`);
  check('file deleted', r.ok);
  if (mode === 'r2') check('r2 object removed', env.FILES.store.size === 0);
  else check('chunks removed', env.DB.raw.prepare('SELECT COUNT(*) c FROM file_chunks').get().c === 0);
  r = await alice.call('DELETE', `/eas/${eaId}`);
  check('EA deleted', r.ok);
}

section('MT5 accounts');
const { env, admin, alice, bob } = await world();
let r = await alice.call('POST', '/accounts', { body: { login: 'abc', server: 'Just-Live', password: 'x' } });
check('bad login rejected', r.status === 400);
r = await alice.call('POST', '/accounts', { body: { login: '1234567', server: 'JustMarkets-Demo', password: 'Secret#Pass1', kind: 'demo', label: 'Main' } });
check('account saved', r.ok);
const accId = r.id;
const row = env.DB.raw.prepare('SELECT * FROM mt5_accounts').get();
check('password encrypted at rest', !JSON.stringify(row).includes('Secret#Pass1') && row.pw_ct.length > 10);
r = await alice.call('GET', '/accounts');
check('list never returns password', !JSON.stringify(r).includes('pw_') && !JSON.stringify(r).includes('Secret') && r.accounts[0].status === 'unverified');
check('status honest without host', /No hosting machine/.test(r.accounts[0].statusDetail), r.accounts[0].statusDetail);
r = await alice.call('POST', '/accounts', { body: { login: '1234567', server: 'JustMarkets-Demo', password: 'x' } });
check('duplicate refused', r.status === 409);
r = await bob.call('GET', '/accounts');
check("other user sees none", r.accounts.length === 0);
r = await bob.call('DELETE', `/accounts/${accId}`);
check("other user cannot delete", r.status === 404);
r = await admin.call('GET', '/admin/accounts');
check('admin sees statuses without secrets', r.accounts.length === 1 && !JSON.stringify(r).includes('Secret') && !JSON.stringify(r).includes('pw_'));
r = await alice.call('PATCH', `/accounts/${accId}`, { body: { password: 'New#Pass22' } });
check('password change ok', r.ok);
const row2 = env.DB.raw.prepare('SELECT pw_ct FROM mt5_accounts').get();
check('ciphertext changed', row2.pw_ct !== row.pw_ct);
r = await alice.call('POST', `/accounts/${accId}/verify`);
check('duplicate pending verify refused', r.status === 409);
check('activity log has no password', !JSON.stringify(env.DB.raw.prepare('SELECT * FROM activity_logs').all()).match(/Secret|New#Pass/));
r = await alice.call('DELETE', `/accounts/${accId}`);
check('account deleted', r.ok);
finish();
